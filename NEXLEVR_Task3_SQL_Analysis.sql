-- Question 1: What is the total monthly revenue generated by the store?
-- We will calculate monthly revenue by joining the orders and order_items tables.

SELECT
    DATE_FORMAT(o.order_date, '%Y-%m') AS month,
    SUM(oi.quantity * oi.unit_price) AS monthly_revenue
FROM orders o
JOIN order_items oi
    ON o.order_id = oi.order_id
WHERE o.order_status = 'Delivered'
GROUP BY DATE_FORMAT(o.order_date, '%Y-%m')
ORDER BY month;

-- Question 2: Who are the top 5 customers based on total spending?
-- We will identify the customers who have spent the most money on delivered orders.

SELECT
    c.customer_id,
    c.customer_name,
    SUM(oi.quantity * oi.unit_price) AS total_spending
FROM customers c
JOIN orders o
    ON c.customer_id = o.customer_id
JOIN order_items oi
    ON o.order_id = oi.order_id
WHERE o.order_status = 'Delivered'
GROUP BY c.customer_id, c.customer_name
ORDER BY total_spending DESC
LIMIT 5;

-- Question 3: Which products generate the highest revenue?
-- We will identify the top-selling products based on revenue.

SELECT
    p.product_name,
    SUM(oi.quantity) AS total_quantity_sold,
    SUM(oi.quantity * oi.unit_price) AS total_revenue
FROM products p
JOIN order_items oi
    ON p.product_id = oi.product_id
JOIN orders o
    ON oi.order_id = o.order_id
WHERE o.order_status = 'Delivered'
GROUP BY p.product_id, p.product_name
ORDER BY total_revenue DESC
LIMIT 5;

-- Question 4: Which cities generate the highest revenue?
-- We will compare sales revenue across different customer cities.

SELECT
    c.city,
    SUM(oi.quantity * oi.unit_price) AS total_revenue
FROM customers c
JOIN orders o
    ON c.customer_id = o.customer_id
JOIN order_items oi
    ON o.order_id = oi.order_id
WHERE o.order_status = 'Delivered'
GROUP BY c.city
ORDER BY total_revenue DESC;

-- Question 5: What is the total number of orders placed by each customer?
-- We will identify how frequently each customer purchases from the store.

SELECT
    c.customer_id,
    c.customer_name,
    COUNT(o.order_id) AS total_orders
FROM customers c
LEFT JOIN orders o
    ON c.customer_id = o.customer_id
GROUP BY c.customer_id, c.customer_name
ORDER BY total_orders DESC;

-- Question 6: Which product categories generate the highest revenue?
-- We will compare revenue across product categories such as Electronics, Furniture, Fashion and Home Appliances.

SELECT
    p.category,
    SUM(oi.quantity) AS total_quantity_sold,
    SUM(oi.quantity * oi.unit_price) AS total_revenue
FROM products p
JOIN order_items oi
    ON p.product_id = oi.product_id
JOIN orders o
    ON oi.order_id = o.order_id
WHERE o.order_status = 'Delivered'
GROUP BY p.category
ORDER BY total_revenue DESC;

-- Question 7: Which customers have not placed any orders?
-- We will identify registered customers who have never purchased from the store.

SELECT
    c.customer_id,
    c.customer_name,
    c.city,
    c.signup_date
FROM customers c
LEFT JOIN orders o
    ON c.customer_id = o.customer_id
WHERE o.order_id IS NULL;

-- Question 8: What is the average order value (AOV)?
-- We will calculate the average amount spent per delivered order.

SELECT
    ROUND(AVG(order_total), 2) AS average_order_value
FROM (
    SELECT
        o.order_id,
        SUM(oi.quantity * oi.unit_price) AS order_total
    FROM orders o
    JOIN order_items oi
        ON o.order_id = oi.order_id
    WHERE o.order_status = 'Delivered'
    GROUP BY o.order_id
) AS order_summary;

-- Question 9: Which customers are inactive or have not purchased recently?
-- We will identify customers whose last delivered order was more than 90 days before the analysis date.

SELECT
    c.customer_id,
    c.customer_name,
    MAX(o.order_date) AS last_order_date,
    DATEDIFF('2023-12-31', MAX(o.order_date)) AS inactive_days
FROM customers c
JOIN orders o
    ON c.customer_id = o.customer_id
WHERE o.order_status = 'Delivered'
GROUP BY c.customer_id, c.customer_name
HAVING DATEDIFF('2023-12-31', MAX(o.order_date)) > 90
ORDER BY inactive_days DESC;

-- Question 10: What is the monthly order status breakdown?
-- We will analyze how many orders were Delivered, Shipped, Cancelled and Returned each month.

SELECT
    DATE_FORMAT(order_date, '%Y-%m') AS month,
    order_status,
    COUNT(order_id) AS total_orders
FROM orders
GROUP BY
    DATE_FORMAT(order_date, '%Y-%m'),
    order_status
ORDER BY month, order_status;